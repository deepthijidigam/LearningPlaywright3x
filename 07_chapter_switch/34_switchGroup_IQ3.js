let browser = "Opera";

switch(browser) {
    case "Chrome":
    case "Brave":
    case "Opera":
        console.log("Chromium Project");
        break;
    case "Firefox":
        console.log("Mozilla project");
        break;
    case "Safari":
        console.log("Apple project");
        break;
    default:
        console.log("Unknown project");
        break;
}